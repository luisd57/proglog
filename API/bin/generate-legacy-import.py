#!/usr/bin/env python3
"""
Generate a Postgres import script from the legacy Prisma/SQLite database.

Usage:
    python3 API/bin/generate-legacy-import.py [data/proglog.db] [API/data/legacy-import.sql]

The old app used cuid primary keys; the new one uses UUID v7. Exercise rows are NOT
imported - the catalog is recreated by `app:seed-exercises`, so every exercise
reference is re-resolved BY NAME via a subquery. Custom exercises (none at time of
writing) are inserted first so their names resolve too.

UUIDs are derived from each row's own timestamp where one exists, keeping v7's
time-ordering meaningful (session ordering uses id as a tiebreak).

Deterministic: same input DB -> same output SQL, so re-running is safe to diff.

Run order on a fresh database:
    make db-migrate
    make sf c='app:seed-exercises'
    psql < legacy-import.sql
"""

import hashlib
import os
import sqlite3
import sys
import uuid
from datetime import datetime
from zoneinfo import ZoneInfo

DB = sys.argv[1] if len(sys.argv) > 1 else "data/proglog.db"
OUT = sys.argv[2] if len(sys.argv) > 2 else "API/data/legacy-import.sql"

# Must match date.timezone in API/docker/php/php.ini.
APP_TZ = ZoneInfo(os.environ.get("APP_TZ", "Europe/Paris"))

# Deterministic UUID v7 generation ------------------------------------------------
# Layout: 48-bit big-endian ms timestamp | version 7 | 12 random-ish bits |
#         variant 10 | 62 bits. We fill the "random" bits from a stable counter
#         keyed by the legacy cuid so output is reproducible.
_counter = {}


def uuid7(ms: int, legacy_id: str) -> str:
    seq = _counter.setdefault(legacy_id, len(_counter) + 1)
    # 74 bits after the version nibble, derived from a STABLE digest of the legacy
    # id (never builtin hash(), which is salted per process) plus a sequence number.
    digest = int.from_bytes(hashlib.sha256(legacy_id.encode()).digest()[:10], "big")
    tail = (digest << 12 | (seq & 0xFFF)) & ((1 << 74) - 1)
    value = (ms & ((1 << 48) - 1)) << 80
    value |= 0x7 << 76
    value |= (tail >> 62) << 64
    value |= 0b10 << 62
    value |= tail & ((1 << 62) - 1)
    return str(uuid.UUID(int=value))


def ts(ms):
    """
    Prisma stored SQLite DateTime as epoch milliseconds (absolute instants).

    The new schema uses TIMESTAMP WITHOUT TIME ZONE - wall-clock time in the app's
    timezone (APP_TZ, matching docker/php/php.ini). Converting to that zone reproduces
    the local times originally shown in the browser when these sessions were logged.
    """
    if ms is None:
        return None
    return datetime.fromtimestamp(ms / 1000, tz=APP_TZ).strftime("%Y-%m-%d %H:%M:%S")


def q(value):
    """Quote a Python value as a Postgres literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def exercise_ref(name):
    """Resolve an exercise by name at import time. Fails loudly (NOT NULL) if absent."""
    return f"(SELECT id FROM exercises WHERE name = {q(name)})"


def main():
    if not os.path.exists(DB):
        sys.exit(f"legacy database not found: {DB}")

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row

    exercises = {r["id"]: r for r in conn.execute("SELECT * FROM Exercise")}
    lines = []
    w = lines.append

    w("-- Generated by API/bin/generate-legacy-import.py - do not edit by hand.")
    w(f"-- Source: {DB}")
    w("-- Prerequisites: migrations applied AND `app:seed-exercises` already run.")
    w("")
    w("BEGIN;")
    w("")

    # Guard: refuse to run twice / on a non-empty database.
    w("DO $$ BEGIN")
    w("  IF (SELECT COUNT(*) FROM sessions) > 0 OR (SELECT COUNT(*) FROM workout_templates) > 0")
    w("     OR (SELECT COUNT(*) FROM measurements) > 0 THEN")
    w("    RAISE EXCEPTION 'Target database already contains data - refusing to import.';")
    w("  END IF;")
    w("  IF (SELECT COUNT(*) FROM exercises) = 0 THEN")
    w("    RAISE EXCEPTION 'Exercise catalog is empty - run app:seed-exercises first.';")
    w("  END IF;")
    w("END $$;")
    w("")

    # --- Custom exercises (built-ins come from the seed) ---------------------
    customs = [r for r in exercises.values() if r["isCustom"]]
    if customs:
        w("-- Custom exercises (not part of the seed catalog)")
        for r in customs:
            w(
                "INSERT INTO exercises (id, name, primary_muscles, secondary_muscles, "
                "equipment, category, instructions, is_custom) VALUES ("
                f"{q(uuid7(0, r['id']))}, {q(r['name'])}, "
                f"{q(r['primaryMuscles'])}, {q(r['secondaryMuscles'])}, "
                f"{q(r['equipment'])}, {q(r['category'])}, {q(r['instructions'])}, TRUE);"
            )
        w("")

    # --- Profile -------------------------------------------------------------
    profile = conn.execute("SELECT * FROM Profile").fetchone()
    if profile:
        birth = ts(profile["birthDate"])
        w("-- Profile (singleton, id = 1)")
        w(
            "INSERT INTO profiles (id, sex, birth_date, default_rest_seconds, height_cm) VALUES ("
            f"1, {q(profile['sex'])}, "
            f"{q(birth[:10]) if birth else 'NULL'}, "
            f"{q(profile['defaultRestSeconds'])}, {q(profile['heightCm'])})"
        )
        w("ON CONFLICT (id) DO UPDATE SET sex = EXCLUDED.sex, birth_date = EXCLUDED.birth_date,")
        w("  default_rest_seconds = EXCLUDED.default_rest_seconds, height_cm = EXCLUDED.height_cm;")
        w("")

    # --- Workout templates ---------------------------------------------------
    tmpl_ids = {}
    templates = list(conn.execute("SELECT * FROM WorkoutTemplate ORDER BY sortOrder, id"))
    if templates:
        w("-- Workout templates")
        for r in templates:
            new_id = uuid7(0, r["id"])
            tmpl_ids[r["id"]] = new_id
            w(
                "INSERT INTO workout_templates (id, name, sort_order, archived_at) VALUES ("
                f"{q(new_id)}, {q(r['name'])}, {q(r['sortOrder'])}, {q(ts(r['archivedAt']))});"
            )
        w("")

    rows = list(conn.execute("SELECT * FROM TemplateExercise ORDER BY templateId, sortOrder"))
    if rows:
        w("-- Template exercise lines")
        for r in rows:
            name = exercises[r["exerciseId"]]["name"]
            w(
                "INSERT INTO template_exercises (id, template_id, exercise_id, sort_order, "
                "target_sets, target_reps, rest_seconds) VALUES ("
                f"{q(uuid7(0, r['id']))}, {q(tmpl_ids[r['templateId']])}, {exercise_ref(name)}, "
                f"{q(r['sortOrder'])}, {q(r['targetSets'])}, {q(r['targetReps'])}, "
                f"{q(r['restSeconds'])});"
            )
        w("")

    # --- Sessions ------------------------------------------------------------
    sess_ids = {}
    sessions = list(conn.execute("SELECT * FROM Session ORDER BY startedAt, id"))
    if sessions:
        w("-- Sessions")
        for r in sessions:
            new_id = uuid7(r["startedAt"] or 0, r["id"])
            sess_ids[r["id"]] = new_id
            tpl = tmpl_ids.get(r["templateId"]) if r["templateId"] else None
            w(
                "INSERT INTO sessions (id, template_id, started_at, finished_at, notes) VALUES ("
                f"{q(new_id)}, {q(tpl)}, {q(ts(r['startedAt']))}, "
                f"{q(ts(r['finishedAt']))}, {q(r['notes'])});"
            )
        w("")

    se_ids = {}
    rows = list(conn.execute("SELECT * FROM SessionExercise ORDER BY sessionId, sortOrder"))
    if rows:
        w("-- Session exercises")
        for r in rows:
            new_id = uuid7(0, r["id"])
            se_ids[r["id"]] = new_id
            name = exercises[r["exerciseId"]]["name"]
            w(
                "INSERT INTO session_exercises (id, session_id, exercise_id, sort_order, notes) "
                f"VALUES ({q(new_id)}, {q(sess_ids[r['sessionId']])}, {exercise_ref(name)}, "
                f"{q(r['sortOrder'])}, {q(r['notes'])});"
            )
        w("")

    rows = list(conn.execute("SELECT * FROM SetLog ORDER BY sessionExerciseId, setNumber"))
    if rows:
        w("-- Set logs")
        for r in rows:
            w(
                "INSERT INTO set_logs (id, session_exercise_id, set_number, weight_kg, reps, "
                "is_warmup, notes) VALUES ("
                f"{q(uuid7(0, r['id']))}, {q(se_ids[r['sessionExerciseId']])}, "
                f"{q(r['setNumber'])}, {q(float(r['weightKg']))}, {q(r['reps'])}, "
                f"{q(bool(r['isWarmup']))}, {q(r['notes'])});"
            )
        w("")

    # --- Measurements --------------------------------------------------------
    rows = list(conn.execute("SELECT * FROM Measurement ORDER BY measuredAt, type"))
    if rows:
        w("-- Measurements")
        for r in rows:
            w(
                "INSERT INTO measurements (id, type, value, measured_at) VALUES ("
                f"{q(uuid7(r['measuredAt'] or 0, r['id']))}, {q(r['type'])}, "
                f"{q(float(r['value']))}, {q(ts(r['measuredAt']))});"
            )
        w("")

    # --- Verification --------------------------------------------------------
    counts = {
        "workout_templates": len(templates),
        "template_exercises": len(list(conn.execute("SELECT 1 FROM TemplateExercise"))),
        "sessions": len(sessions),
        "session_exercises": len(se_ids),
        "set_logs": len(list(conn.execute("SELECT 1 FROM SetLog"))),
        "measurements": len(rows),
    }
    w("-- Row-count verification: aborts the transaction on any mismatch.")
    w("DO $$ BEGIN")
    for table, expected in counts.items():
        w(f"  IF (SELECT COUNT(*) FROM {table}) <> {expected} THEN")
        w(f"    RAISE EXCEPTION '{table}: expected {expected}, got %', (SELECT COUNT(*) FROM {table});")
        w("  END IF;")
    w("END $$;")
    w("")
    w("COMMIT;")
    w("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print(f"wrote {OUT}")
    for table, expected in counts.items():
        print(f"  {table}: {expected}")
    if customs:
        print(f"  custom exercises: {len(customs)}")


if __name__ == "__main__":
    main()
